import { test } from 'node:test';
import assert from 'node:assert/strict';
import { promises as fs } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { writeAgentsMd, writeMirrors } from '../src/render/write.ts';
import { BEGIN_MARKER, END_MARKER } from '../src/render/agents-md.ts';

async function tempDir(): Promise<string> {
  return fs.mkdtemp(path.join(os.tmpdir(), 'devtools-agents-'));
}

test('creates the file with a managed block and a free form notes section', async () => {
  const dir = await tempDir();
  const target = path.join(dir, 'AGENTS.md');
  const result = await writeAgentsMd(target, '# Title\n\nbody', { lang: 'en' });

  assert.equal(result.action, 'created');
  const content = await fs.readFile(target, 'utf8');
  assert.ok(content.includes(BEGIN_MARKER));
  assert.ok(content.includes(END_MARKER));
  assert.ok(content.includes('body'));
  assert.ok(content.includes('Project-specific notes'));
});

test('preserves content outside the managed block on regeneration', async () => {
  const dir = await tempDir();
  const target = path.join(dir, 'AGENTS.md');
  await fs.writeFile(target, '# My project rules\n\nAlways be nice.\n', 'utf8');

  const first = await writeAgentsMd(target, 'generated v1', { lang: 'en' });
  assert.equal(first.action, 'updated');

  // A different body always writes; the stable-environment optimisation does not
  // prevent a body that differs.
  const second = await writeAgentsMd(target, 'generated v2', { lang: 'en' });
  assert.equal(second.action, 'updated');

  const content = await fs.readFile(target, 'utf8');
  assert.ok(content.includes('Always be nice.'));
  assert.ok(content.includes('generated v2'));
  assert.ok(!content.includes('generated v1'));
});

test('is idempotent when nothing changed', async () => {
  const dir = await tempDir();
  const target = path.join(dir, 'AGENTS.md');
  await writeAgentsMd(target, 'same body', { lang: 'en' });
  const result = await writeAgentsMd(target, 'same body', { lang: 'en' });
  assert.equal(result.action, 'unchanged');
});

test('keeps the previous block, timestamp included, when only the clock moved', async () => {
  const dir = await tempDir();
  const target = path.join(dir, 'AGENTS.md');
  const body = (timestamp: string) =>
    `# Doc\n\n> Generated by \`devtools-agents\` · ${timestamp} UTC · env \`abc123\`\n\n## Stack\nnode\n`;

  await writeAgentsMd(target, body('2026-10-23 09:00:00'), { lang: 'en' });
  const first = await fs.readFile(target, 'utf8');

  const result = await writeAgentsMd(target, body('2026-10-23 09:05:00'), { lang: 'en' });
  assert.equal(result.action, 'unchanged');

  const second = await fs.readFile(target, 'utf8');
  assert.equal(second, first);
  assert.ok(second.includes('2026-10-23 09:00:00'), 'the original timestamp must survive');
});

test('a different environment with the same timestamp still rewrites the block', async () => {
  const dir = await tempDir();
  const target = path.join(dir, 'AGENTS.md');
  const body = (fingerprint: string, extra: string) =>
    `# Doc\n\n> Generated by \`devtools-agents\` · 2026-10-23 09:00:00 UTC · env \`${fingerprint}\`\n\n${extra}\n`;

  await writeAgentsMd(target, body('abc123', 'node'), { lang: 'en' });
  const result = await writeAgentsMd(target, body('abc123', 'node, python'), { lang: 'en' });
  assert.equal(result.action, 'updated');
  const content = await fs.readFile(target, 'utf8');
  assert.ok(content.includes('node, python'));
});

test('repairs a truncated managed block instead of appending a second one', async () => {
  const dir = await tempDir();
  const target = path.join(dir, 'AGENTS.md');
  await fs.writeFile(target, `# Notes\n\n${BEGIN_MARKER}\nhalf written\n`, 'utf8');

  const result = await writeAgentsMd(target, 'fresh body', { lang: 'en' });
  assert.equal(result.action, 'updated');

  const content = await fs.readFile(target, 'utf8');
  const count = (needle: string) => content.split(needle).length - 1;
  assert.equal(count(BEGIN_MARKER), 1);
  assert.equal(count(END_MARKER), 1);
  assert.ok(content.indexOf(BEGIN_MARKER) < content.indexOf(END_MARKER));
  assert.ok(content.includes('fresh body'));
  assert.ok(content.includes('# Notes'));

  const again = await writeAgentsMd(target, 'fresh body', { lang: 'en' });
  assert.equal(again.action, 'unchanged');
});

test('force mode replaces the whole file', async () => {
  const dir = await tempDir();
  const target = path.join(dir, 'AGENTS.md');
  await fs.writeFile(target, 'human text', 'utf8');
  const result = await writeAgentsMd(target, 'body', { lang: 'en', force: true });
  assert.equal(result.action, 'updated');
  const content = await fs.readFile(target, 'utf8');
  assert.ok(!content.includes('human text'));
});

test('mirrors write pointer files for claude and gemini', async () => {
  const dir = await tempDir();
  const results = await writeMirrors(dir, 'body', ['claude', 'gemini'], 'en');
  assert.equal(results.length, 2);
  const claude = await fs.readFile(path.join(dir, 'CLAUDE.md'), 'utf8');
  assert.ok(claude.includes('@AGENTS.md'));
  const gemini = await fs.readFile(path.join(dir, 'GEMINI.md'), 'utf8');
  assert.ok(gemini.includes('@AGENTS.md'));
});

test('copilot mirror copies the full content', async () => {
  const dir = await tempDir();
  await writeMirrors(dir, 'the real body', ['copilot'], 'en');
  const content = await fs.readFile(path.join(dir, '.github', 'copilot-instructions.md'), 'utf8');
  assert.ok(content.includes('the real body'));
});

test('copilot mirror replaces its previous copy instead of appending', async () => {
  const dir = await tempDir();
  const file = path.join(dir, '.github', 'copilot-instructions.md');
  await writeMirrors(dir, 'first body', ['copilot'], 'en');
  const first = await fs.readFile(file, 'utf8');

  const second = await writeMirrors(dir, 'first body', ['copilot'], 'en');
  assert.equal(second[0]?.action, 'unchanged');
  assert.equal(await fs.readFile(file, 'utf8'), first);

  await writeMirrors(dir, 'second body', ['copilot'], 'en');
  const third = await fs.readFile(file, 'utf8');
  assert.ok(third.includes('second body'));
  assert.ok(!third.includes('first body'));
  assert.equal(third.split('devtools-agents:begin').length - 1, 1);
});

test('copilot mirror keeps hand written text that precedes the managed block', async () => {
  const dir = await tempDir();
  const file = path.join(dir, '.github', 'copilot-instructions.md');
  await fs.mkdir(path.dirname(file), { recursive: true });
  await fs.writeFile(file, '# House rules\n\nBe careful.\n', 'utf8');

  const result = await writeMirrors(dir, 'mirrored body', ['copilot'], 'en');
  assert.equal(result[0]?.action, 'merged');
  const content = await fs.readFile(file, 'utf8');
  assert.ok(content.includes('Be careful.'));
  assert.ok(content.includes('mirrored body'));
});
