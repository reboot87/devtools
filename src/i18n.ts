export type StringId = keyof (typeof DICTIONARY)['en'];

export function translator(lang: Lang): (id: StringId) => string {
  return (id) => DICTIONARY[lang][id] ?? DICTIONARY.en[id] ?? id;
}

export function resolveLang(value: string | undefined): Lang {
  if (!value) return 'zh';
  const normalized = value.toLowerCase();
  if (normalized.startsWith('zh')) return 'zh';
  if (normalized.startsWith('en')) return 'en';
  return 'zh';
}
